package practice;

public class Switch 
{
	public static void main(String[]args)
	{
		int x=8;
		switch(x)
		{
		case 1 : 
		System.out.println("Yes");
		break;
		
		case 2 :
		System.out.println("No");
		break;
		
		default :
		System.out.println("Enter a valid no");
		}
		System.out.println();
	}
}
