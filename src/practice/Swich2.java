package practice;

public class Swich2 
{
	public static void main(String[]args)
	{
		int x=1;
		switch(x)
		{
		case 1 :
			System.out.println("East");
			
		case 2 :
			System.out.println("West");
			
		case 3 :
			System.out.println("North");
			
		case 4 :
			System.out.println("South");
			
			default :
				System.out.println("Enter valid input");
		}
	}
}
